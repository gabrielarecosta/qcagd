-- 2. Tabla específica para postulaciones y solicitudes de admisión mayorista
CREATE TABLE IF NOT EXISTS wholesale_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT REFERENCES customers(id) ON DELETE SET NULL,
    nombre TEXT NOT NULL,
    dni TEXT,
    razon_social TEXT NOT NULL,
    cuit TEXT NOT NULL,
    rubro TEXT NOT NULL,
    telefono TEXT NOT NULL,
    email TEXT NOT NULL,
    direccion TEXT NOT NULL,
    localidad TEXT NOT NULL,
    provincia TEXT DEFAULT 'Córdoba',
    volumen_estimado TEXT,
    notas TEXT,
    estado TEXT DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'aprobada', 'rechazada')),
    revisado_por TEXT,
    fecha_solicitud TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    fecha_resolucion TIMESTAMPTZ,
    motivo_rechazo TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- Índices para búsqueda rápida de solicitudes pendientes
CREATE INDEX IF NOT EXISTS idx_wholesale_applications_estado ON wholesale_applications(estado);
CREATE INDEX IF NOT EXISTS idx_wholesale_applications_customer_id ON wholesale_applications(customer_id);
CREATE INDEX IF NOT EXISTS idx_wholesale_applications_email ON wholesale_applications(email);

-- 3. Funciones RPC para aceptación y rechazo directo desde Admin
CREATE OR REPLACE FUNCTION approve_wholesale_application(
    p_customer_id BIGINT,
    p_admin_email TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_updated_count INT;
BEGIN
    -- Actualizar el cliente como mayorista autorizado
    UPDATE customers
    SET 
        tipo_cliente = 'mayorista',
        mayorista_autorizado = TRUE,
        estado_solicitud_mayorista = 'aprobada',
        fecha_resolucion_mayorista = NOW(),
        updated_at = NOW()
    WHERE id = p_customer_id;
    
    GET DIAGNOSTICS v_updated_count = ROW_COUNT;
    IF v_updated_count = 0 THEN
        RETURN jsonb_build_object('success', false, 'error', 'Cliente no encontrado');
    END IF;

    -- Actualizar la solicitud en la tabla de admisiones si existe
    UPDATE wholesale_applications
    SET 
        estado = 'aprobada',
        fecha_resolucion = NOW(),
        revisado_por = p_admin_email,
        updated_at = NOW()
    WHERE customer_id = p_customer_id AND estado = 'pendiente';

    RETURN jsonb_build_object(
        'success', true, 
        'customer_id', p_customer_id, 
        'estado', 'aprobada',
        'mensaje', 'Cliente aprobado como mayorista exitosamente.'
    );
END;
$$;

CREATE OR REPLACE FUNCTION reject_wholesale_application(
    p_customer_id BIGINT,
    p_motivo TEXT DEFAULT NULL,
    p_admin_email TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_updated_count INT;
BEGIN
    -- Actualizar el cliente a minorista con nota de rechazo
    UPDATE customers
    SET 
        tipo_cliente = 'minorista',
        mayorista_autorizado = FALSE,
        estado_solicitud_mayorista = 'rechazada',
        fecha_resolucion_mayorista = NOW(),
        motivo_rechazo_mayorista = p_motivo,
        observaciones = COALESCE(observaciones || E'\n', '') || '[RECHAZADO MAYORISTA: ' || COALESCE(p_motivo, 'Requisitos no cumplidos') || ' el ' || TO_CHAR(NOW(), 'DD/MM/YYYY') || ']',
        updated_at = NOW()
    WHERE id = p_customer_id;
    
    GET DIAGNOSTICS v_updated_count = ROW_COUNT;
    IF v_updated_count = 0 THEN
        RETURN jsonb_build_object('success', false, 'error', 'Cliente no encontrado');
    END IF;

    -- Actualizar la solicitud en la tabla de admisiones si existe
    UPDATE wholesale_applications
    SET 
        estado = 'rechazada',
        fecha_resolucion = NOW(),
        motivo_rechazo = p_motivo,
        revisado_por = p_admin_email,
        updated_at = NOW()
    WHERE customer_id = p_customer_id AND estado = 'pendiente';

    RETURN jsonb_build_object(
        'success', true, 
        'customer_id', p_customer_id, 
        'estado', 'rechazada',
        'mensaje', 'Solicitud mayorista rechazada correctamente.'
    );
END;
$$;

-- 4. Habilitar Seguridad RLS y Políticas de acceso (sin usar DROP)
ALTER TABLE wholesale_applications ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
    -- Permitir inserción pública de formularios
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE tablename = 'wholesale_applications' 
          AND policyname = 'Permitir insercion publica de postulaciones mayoristas'
    ) THEN
        CREATE POLICY "Permitir insercion publica de postulaciones mayoristas"
            ON wholesale_applications FOR INSERT TO public WITH CHECK (true);
    END IF;

    -- Permitir lectura
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE tablename = 'wholesale_applications' 
          AND policyname = 'Permitir lectura de postulaciones mayoristas'
    ) THEN
        CREATE POLICY "Permitir lectura de postulaciones mayoristas"
            ON wholesale_applications FOR SELECT TO public USING (true);
    END IF;

    -- Permitir actualización
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies 
        WHERE tablename = 'wholesale_applications' 
          AND policyname = 'Permitir actualizacion de postulaciones mayoristas'
    ) THEN
        CREATE POLICY "Permitir actualizacion de postulaciones mayoristas"
            ON wholesale_applications FOR UPDATE TO public USING (true) WITH CHECK (true);
    END IF;
END $$;

